"""Домашняя страница и политика конфиденциальности (Phase 64, довесок)
— нужны для верификации Google OAuth consent screen (Application home
page / Privacy policy link в разделе Branding), больше ни для чего не
используются. Тот же минимальный стиль страницы, что у web_auth.py/
google_oauth.py — не шарим между модулями сознательно, три маленьких
независимых копии проще, чем один общий импорт ради разметки.

Название приложения (заголовок обеих страниц) должно быть буквально
той же строкой, что в поле App name на вкладке Branding в Google Cloud
Console — Google это сверяет при верификации (первая попытка отклонена
именно за расхождение названий, см. SPEC.md)."""

from fastapi import APIRouter
from fastapi.responses import HTMLResponse

router = APIRouter()

_APP_NAME = "Личный ассистент chitinez"

_PAGE_STYLE = """
<style>
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif;
    background: #f2f2f2; color: #111; margin: 0; padding: 32px 20px;
    line-height: 1.6; }
  .card { max-width: 560px; margin: 0 auto; }
  h1 { font-size: 22px; margin: 0 0 8px; }
  h2 { font-size: 16px; margin: 24px 0 6px; }
  p, li { font-size: 14px; color: #333; }
  a { color: #2481cc; }
  ul { padding-left: 20px; margin: 6px 0; }
</style>
"""


def _page(body: str) -> HTMLResponse:
    html = (
        f"<!doctype html><html><head>{_PAGE_STYLE}</head>"
        f"<body><div class='card'>{body}</div></body></html>"
    )
    return HTMLResponse(html)


@router.get("/")
async def homepage() -> HTMLResponse:
    return _page(f"""
    <h1>{_APP_NAME}</h1>
    <p>Telegram-бот и мини-приложение для личного управления задачами,
    привычками, дневником и заметками. Голосовые и текстовые сообщения
    боту разбираются автоматически и превращаются в задачи, напоминания
    или записи дневника.</p>
    <p>Доступ к боту даётся по паролю от владельца — это не открытая
    публичная регистрация, но и не фиксированный список из нескольких
    человек: пароль может получить любой, кому его выдал владелец. Если
    вы получили ссылку сюда из экрана согласия Google — это
    подтверждение, что бот, запрашивающий доступ к календарю, реально
    существует и принадлежит тому, кто вас пригласил.</p>
    <p>Дополнительно бот умеет читать события основного Google Calendar
    (только чтение) и создавать по ним задачи со временем — подробнее в
    <a href="/privacy">политике конфиденциальности</a>.</p>
    """)


@router.get("/privacy")
async def privacy_policy() -> HTMLResponse:
    return _page(f"""
    <h1>Политика конфиденциальности — {_APP_NAME}</h1>
    <p>{_APP_NAME} — Telegram-бот и мини-приложение для управления
    задачами, привычками, дневником и заметками. Доступ выдаётся
    владельцем бота по паролю — открытой публичной регистрации нет, но
    круг пользователей не ограничен заранее известным списком людей.
    Ниже — какие данные обрабатываются и зачем.</p>

    <h2>Какие данные обрабатываются</h2>
    <ul>
      <li>Текст и голосовые сообщения, которые вы присылаете боту в
        Telegram — распознаются (Groq Whisper) и разбираются (Claude,
        Anthropic) на задачи/заметки/записи дневника/напоминания.</li>
      <li>Ваш Telegram-идентификатор — для разделения данных между
        приглашёнными пользователями.</li>
      <li>С вашего явного согласия — события основного Google Calendar
        (только чтение, scope calendar.readonly): название, время,
        статус. Используется исключительно для создания и обновления
        соответствующих задач в приложении.</li>
      <li>По желанию — геопозиция (для часового пояса и локальной
        погоды в утренней сводке).</li>
    </ul>

    <h2>Где хранится и с кем не делится</h2>
    <p>Все данные хранятся в собственной базе данных (Postgres) на
    сервере владельца бота — не продаются, не передаются рекламным
    сетям и другим третьим лицам. Сторонним сервисам данные передаются
    только в объёме, необходимом для работы конкретной функции:
    распознавание речи (Groq), обработка текста (Claude API через
    прокси Anthropic), доступ к календарю (Google Calendar API),
    погода (Open-Meteo, без персональных данных).</p>

    <h2>Отзыв доступа к Google Calendar</h2>
    <p>Отключить синхронизацию можно в любой момент командой
    <code>/google_calendar_off</code> в самом боте, либо отозвав доступ
    приложению в настройках своего Google-аккаунта
    (myaccount.google.com/permissions). После отключения уже созданные
    из календаря задачи остаются в приложении как обычные, независимые
    от календаря.</p>

    <h2>Удаление данных</h2>
    <p>Чтобы удалить все свои данные из приложения — напишите
    владельцу бота напрямую в Telegram.</p>
    """)
