"""Версионирование статики Mini App (Phase 96, фидбек: "давай поработаем
над статикой") — query-string cache-busting для CSS/JS под `/miniapp/css`
и `/miniapp/js`, чтобы браузер/Telegram WebView мог кэшировать их надолго
между деплоями, где они не менялись, но гарантированно перекачивал
заново, когда менялись. `index.html`, `manifest.json`, иконки,
`service-worker.js` — по-прежнему `no-store` (см.
`api.py::_no_cache_miniapp`, Phase 88) — и это ключевая часть схемы, не
просто "не успели": `index.html` обязан быть всегда свежим, чтобы в нём
был актуальный `?v=...` на остальное, иначе версионирование не работает.

Как это устроено:

1. `get_asset_version()` — ОДИН хэш на весь набор CSS+JS (не по файлу
   отдельно), вычисляется один раз за время жизни процесса (файлы в
   образе не меняются, пока контейнер не пересоздан следующим деплоем,
   см. тот же lazy-singleton приём, что уже в `core/login_codes.py` и
   соседях). Любое изменение любого файла меняет хэш — значит меняются
   ВСЕ ссылки на статику сразу, не только изменившийся файл. Чуть
   расточительнее честного per-file хэширования (лишний рефетч файлов,
   которые реально не менялись в этом деплое), зато на порядок проще и
   так же безопасно по корректности — ложной бессрочной инвалидации не
   бывает (есть реальное изменение контента → есть новый хэш), ложного
   "НЕ инвалидировать, хотя поменялось" тоже (сервер не умеет соврать
   себе, что контент не поменялся).

2. `version_asset_refs()` переписывает в тексте файла каждую ссылку вида
   `/miniapp/css/*.css`, `/miniapp/js/**/*.js` (абсолютные — так
   ссылается на статику сам `index.html`) и `./*.js` (относительные
   ES-module импорты — ТАК ссылаются друг на друга сами JS-файлы, см.
   `panel.js` → `./registry.js` → `./sphere-chart.js` и т.д.) в
   `...?v=<ASSET_VERSION>`. Если версионировать только ссылки в
   `index.html` и оставить относительные импорты внутри JS как есть, то
   `panel.js`/`registry.js` получили бы длинный `immutable` кэш на
   НЕверсионированный URL — ровно тот же баг Telegram WebView, из-за
   которого в своё время поставили блэнкет `no-store` (Phase 88), только
   теперь уже не лечится самим `no-store`, раз мы специально включаем
   долгое кэширование для этих путей. Поэтому `.js`-файлы отдаются через
   отдельный маршрут (`api.py::serve_versioned_js`), который прогоняет
   их через тот же `version_asset_refs()`, а не через голый
   `StaticFiles` — единообразно для всех JS, включая будущие файлы с
   новыми относительными импортами, не только два, у которых они есть
   сегодня.

3. `service-worker.js` — НЕ версионируется и не переписывается этим
   механизмом: регистрация service worker'а подчиняется отдельным
   браузерным правилам кэширования (большинство браузеров сами не дают
   закэшировать сам файл воркера дольше суток, что бы ни было в
   заголовках) — применять к нему тот же приём было бы лишним риском без
   выгоды, он и так крошечный (12 строк) и меняется редко.

Почему это безопасно даже если баг Phase 88 как-то повторится (WebView
всё-таки закэширует старый `index.html` вопреки `no-store`): он продолжит
запрашивать старые `?v=oldhash` URL для CSS/JS — сервер их всё равно
корректно отдаст (query-string не влияет на то, какой файл сервер ищет на
диске, только на то, что БРАУЗЕР считает уникальным URL для своего кэша),
просто отдаст уже ТЕКУЩЕЕ содержимое файла под "старым" версионным именем
— не ломает ничего функционально, худший случай — смесь старой разметки
со свежим CSS/JS, что не хуже сегодняшнего статус-кво (там с `no-store`
всё и так перекачивается заново при каждом открытии, просто без всякого
выигрыша от кэша)."""

import hashlib
import re
from pathlib import Path

_ASSET_REF_PATTERN = re.compile(
    r'(?P<quote>["\'])'
    r'(?P<path>/miniapp/(?:css|js)/[^"\']+\.(?:css|js)|\./[^"\']+\.js)'
    r"(?P=quote)"
)

_asset_version_cache: str | None = None


def get_asset_version(static_dir: Path) -> str:
    """Короткий хэш содержимого всей css/+js/ (см. объяснение в шапке
    модуля) — вычисляется один раз за время жизни процесса."""
    global _asset_version_cache
    if _asset_version_cache is not None:
        return _asset_version_cache

    hasher = hashlib.sha256()
    files = sorted(
        [*(static_dir / "css").rglob("*.css"), *(static_dir / "js").rglob("*.js")],
        key=lambda p: p.relative_to(static_dir).as_posix(),
    )
    for file_path in files:
        hasher.update(file_path.relative_to(static_dir).as_posix().encode("utf-8"))
        hasher.update(file_path.read_bytes())

    _asset_version_cache = hasher.hexdigest()[:12]
    return _asset_version_cache


def version_asset_refs(text: str, version: str) -> str:
    """Дописывает `?v=<version>` к каждой ссылке на CSS/JS (абсолютной
    `/miniapp/css|js/...` или относительной `./*.js`) — см. объяснение в
    шапке модуля. Всё остальное (manifest.json, иконки, API-вызовы,
    service-worker.js) не трогает: паттерн их не матчит."""

    def _append_version(match: re.Match[str]) -> str:
        quote = match.group("quote")
        path = match.group("path")
        return f"{quote}{path}?v={version}{quote}"

    return _ASSET_REF_PATTERN.sub(_append_version, text)
